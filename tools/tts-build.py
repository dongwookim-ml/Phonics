"""Records every phrase in tools/tts-phrases.json with the Kokoro voice model.

Setup (once):
    pip install kokoro-onnx soundfile
    curl -LO https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/kokoro-v1.0.int8.onnx
    curl -LO https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/voices-v1.0.bin
Run:
    node tools/tts-phrases.js
    python tools/tts-build.py --model kokoro-v1.0.int8.onnx --voices voices-v1.0.bin

Clips already recorded are kept. Writes audio/tts/<voice>/<id>.mp3 and
audio/tts/index.js, which the game loads to find them. Needs ffmpeg.
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from multiprocessing import Pool

import numpy as np
import soundfile as sf

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'audio', 'tts')
TRIM = ('silenceremove=start_periods=1:start_threshold=-45dB,areverse,'
        'silenceremove=start_periods=1:start_threshold=-45dB,areverse,apad=pad_dur=0.08')

kokoro = None

# The voice model reads letter sounds like "hhh" as letter names ("aitch aitch
# aitch") and "eh" as the letter A, so lines made only of these sounds are
# recorded from phonemes instead. Keys match LETTERS and PART_SOUNDS in data.js.
SOUND_IPA = {
    'ah': 'ˈæ', 'eh': 'ˈɛ', 'ih': 'ˈɪ', 'aw': 'ˈɑː', 'uh': 'ˈʌ',
    'fff': 'fˈə', 'hhh': 'hˈə', 'mmm': 'mˈə', 'nnn': 'nˈə', 'sss': 'sˈə', 'lll': 'lˈə', 'rrr': 'ɹˈə',
    'ks': 'ks',
    # Letter names, for the spelling tiles: a lone "A" is read as the word "a".
    'A': 'ˈA', 'B': 'bˈi', 'C': 'sˈi', 'D': 'dˈi', 'E': 'ˈi', 'F': 'ˈɛf', 'G': 'ʤˈi', 'H': 'ˈAʧ', 'I': 'ˈI',
    'J': 'ʤˈA', 'K': 'kˈA', 'L': 'ˈɛl', 'M': 'ˈɛm', 'N': 'ˈɛn', 'O': 'ˈO', 'P': 'pˈi', 'Q': 'kjˈu', 'R': 'ˈɑɹ',
    'S': 'ˈɛs', 'T': 'tˈi', 'U': 'jˈu', 'V': 'vˈi', 'W': 'dˈʌbəlju', 'X': 'ˈɛks', 'Y': 'wˈI', 'Z': 'zˈi',
}


def phonemes(text):
    words = [w.strip() for w in text.split(',')]
    if all(w in SOUND_IPA for w in words):
        return ', '.join(SOUND_IPA[w] for w in words)
    return None


def clip_id(p):
    key = f"{p['voice']}|{p['text']}|{p['speed']}"
    ipa = phonemes(p['text'])
    if ipa:
        key += f'|{ipa}'
    return hashlib.sha1(key.encode()).hexdigest()[:10]


def init(model, voices):
    global kokoro
    from kokoro_onnx import Kokoro
    kokoro = Kokoro(model, voices)


def record(p):
    path = os.path.join(OUT, p['voice'], clip_id(p) + '.mp3')
    if os.path.exists(path):
        return p, True
    ipa = phonemes(p['text'])
    samples, rate = kokoro.create(ipa or p['text'], voice=p['voice'], speed=p['speed'], lang='en-us',
                                  is_phonemes=bool(ipa))
    with tempfile.NamedTemporaryFile(suffix='.wav') as wav:
        sf.write(wav.name, samples, rate)
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', wav.name, '-af', TRIM,
                        '-ac', '1', '-ar', '24000', '-b:a', '48k', path], check=True)
    return p, True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--model', default='kokoro-v1.0.int8.onnx')
    ap.add_argument('--voices', default='voices-v1.0.bin')
    ap.add_argument('--jobs', type=int, default=os.cpu_count() or 2)
    args = ap.parse_args()
    phrases = json.load(open(os.path.join(ROOT, 'tools', 'tts-phrases.json')))
    for v in {p['voice'] for p in phrases}:
        os.makedirs(os.path.join(OUT, v), exist_ok=True)
    silence = os.path.join(OUT, 'silence.mp3')
    if not os.path.exists(silence):
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-f', 'lavfi', '-i', 'anullsrc=r=24000:cl=mono',
                        '-t', '0.1', '-b:a', '32k', silence], check=True)
    todo = [p for p in phrases if not os.path.exists(os.path.join(OUT, p['voice'], clip_id(p) + '.mp3'))]
    print(f'{len(phrases)} phrases, {len(todo)} to record', flush=True)
    with Pool(args.jobs, initializer=init, initargs=(args.model, args.voices)) as pool:
        for i, _ in enumerate(pool.imap_unordered(record, todo, chunksize=4), 1):
            if i % 100 == 0:
                print(f'  {i}/{len(todo)}', flush=True)
    index = {}
    for p in phrases:
        index.setdefault(p['voice'], {})[p['text']] = clip_id(p)
    # Drop recordings that no phrase uses any more.
    keep = {(v, i) for v, m in index.items() for i in m.values()}
    for v in os.listdir(OUT):
        d = os.path.join(OUT, v)
        if os.path.isdir(d):
            for f in os.listdir(d):
                if (v, f[:-4]) not in keep:
                    os.remove(os.path.join(d, f))
    with open(os.path.join(OUT, 'index.js'), 'w') as f:
        f.write('// Generated by tools/tts-build.py: voice -> sentence -> recording id.\n')
        f.write('const TTS_INDEX = ' + json.dumps(index, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print('done', flush=True)


if __name__ == '__main__':
    sys.exit(main())
